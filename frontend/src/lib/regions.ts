const GWANGJU_DISTRICTS = new Set(["동구", "서구", "남구", "북구", "광산구"]);

/** eligible_region 매칭용 짧은 지역 토큰 계산. 전남광주통합특별시는 옛 광주/전남 중 어느
 * 쪽 하위 지역을 골랐는지에 따라 "광주" 또는 "전남"으로 나눠서 돌려줌(기존 DB 데이터가
 * 그 관례를 씀). */
export function regionShortName(sidoName: string, district: string): string {
  if (sidoName === "전남광주통합특별시") {
    return GWANGJU_DISTRICTS.has(district) ? "광주" : "전남";
  }
  return SIDO_LIST.find((s) => s.name === sidoName)?.shortName ?? sidoName;
}
