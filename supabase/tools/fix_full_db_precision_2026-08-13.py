def load_database_url() -> str:
    env_path = Path(__file__).resolve().parents[2] / "backend" / ".env"
    for line in env_path.read_text(encoding="utf-8").splitlines():
        if line.startswith("DATABASE_URL="):
            return line.split("=", 1)[1].strip()
    raise RuntimeError(f"DATABASE_URL not found in {env_path}")


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    apply = "--apply" in sys.argv
    conn = psycopg2.connect(load_database_url())
    cur = conn.cursor()

    all_ids = sorted(set(PERIOD_FIXES) | set(DEADLINE_FIXES) | set(NAME_FIXES))
    cur.execute(
        "SELECT id, name, application_period, application_deadline "
        "FROM scholarship WHERE id = ANY(%s) ORDER BY id",
        (all_ids,),
    )
    before_rows = {r[0]: r for r in cur.fetchall()}

    missing = [i for i in all_ids if i not in before_rows]
    if missing:
        print(f"경고: DB에 없는 id {missing} — 스킵")

    changed = 0
    for sid in all_ids:
        if sid not in before_rows:
            continue
        before = before_rows[sid]
        new_name = NAME_FIXES.get(sid, before[1])
        new_period = PERIOD_FIXES.get(sid, before[2])
        new_deadline = DEADLINE_FIXES.get(sid, before[3])
        if (
            new_name == before[1]
            and new_period == before[2]
            and str(new_deadline) == str(before[3])
        ):
            continue
        changed += 1
        cur.execute(
            "UPDATE scholarship SET name = %s, application_period = %s, "
            "application_deadline = %s WHERE id = %s",
            (new_name, new_period, new_deadline, sid),
        )

    cur.execute(
        "SELECT id, name, application_period, application_deadline "
        "FROM scholarship WHERE id = ANY(%s) ORDER BY id",
        (all_ids,),
    )
    after_rows = {r[0]: r for r in cur.fetchall()}

    for sid in all_ids:
        if sid not in before_rows:
            continue
        before = before_rows[sid]
        after = after_rows[sid]
        if before == after:
            continue
        print(f"id={sid} {before[1]}")
        if before[1] != after[1]:
            print(f"  name 전: {before[1]!r}")
            print(f"  name 후: {after[1]!r}")
        if before[2] != after[2]:
            print(f"  period 전: {before[2]!r}")
            print(f"  period 후: {after[2]!r}")
        if before[3] != after[3]:
            print(f"  deadline 전: {before[3]!r}")
            print(f"  deadline 후: {after[3]!r}")

    print(f"\n총 {len(all_ids)}건 대상, {changed}건 변경.")

    if apply:
        conn.commit()
        print("반영 완료(commit).")
    else:
        conn.rollback()
        print("dry-run만 수행(rollback, 실제 반영 안 됨).")

    cur.close()
    conn.close()


if __name__ == "__main__":
    main()
