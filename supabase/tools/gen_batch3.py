DATE_COLUMNS = {"application_deadline"}
BOOL_COLUMNS = {"requires_disability"}
ARRAY_COLUMNS = {"required_special_status"}


def esc(s: str) -> str:
    return s.replace("'", "''")


def render_value(col: str, row: dict):
    if col not in row or row[col] is None:
        if col in ARRAY_COLUMNS:
            return "'{}'"
        return "NULL"
    v = row[col]
    if col in ARRAY_COLUMNS:
        items = v if isinstance(v, list) else [v]
        if not items:
            return "'{}'"
        return "'{" + ",".join(items) + "}'"
    if col in BOOL_COLUMNS:
        return "TRUE" if v else "FALSE"
    if col in DATE_COLUMNS:
        return f"'{v}'"
    if col in TEXT_COLUMNS:
        return f"'{esc(str(v))}'"
    # numeric (amount, ages, income bracket, gpa, credits/grade ints)
    return str(v)


def render_row(row: dict) -> str:
    values = [render_value(c, row) for c in COLUMNS]
    return "(" + ", ".join(values) + ")"


def generate(rows: list[dict]) -> str:
    header = "INSERT INTO scholarship (" + ", ".join(COLUMNS) + ") VALUES\n"
    body = ",\n\n".join(render_row(r) for r in rows)
    return header + body + ";\n"


