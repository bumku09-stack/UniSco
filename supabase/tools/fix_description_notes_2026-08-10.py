def main() -> None:
    apply = "--apply" in sys.argv
    conn = psycopg2.connect(load_database_url())
    cur = conn.cursor()

    ids = [f["id"] for f in FIXES]
    cur.execute(
        "SELECT id, name, description FROM scholarship WHERE id = ANY(%s) ORDER BY id",
        (ids,),
    )
    before_rows = {r[0]: r for r in cur.fetchall()}

    if len(before_rows) != len(set(ids)):
        missing = set(ids) - set(before_rows)
        print(f"경고: DB에서 못 찾은 id 있음: {missing}")

    for fix in FIXES:
        cur.execute(
            "UPDATE scholarship SET description = %s WHERE id = %s",
            (fix["description"], fix["id"]),
        )
        if cur.rowcount != 1:
            print(f"!! id={fix['id']}: UPDATE 영향받은 행 수 = {cur.rowcount} (예상: 1)")

    report_lines = []
    for fix in FIXES:
        fid = fix["id"]
        before = before_rows.get(fid)
        if before is None:
            continue
        name = before[1]
        old_desc = before[2] or ""
        new_desc = fix["description"]
        report_lines.append(f"\n## id={fid} {name}")
        report_lines.append(f"- BEFORE: {old_desc}")
        report_lines.append(f"- AFTER:  {new_desc}")

    report = "\n".join(report_lines)
    out_path = Path(__file__).resolve().parents[1] / "audit_reports" / "fix_description_notes_2026-08-10_diff.md"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(report, encoding="utf-8")

    if apply:
        conn.commit()
        print(f"반영 완료(commit). {len(FIXES)}건 처리. diff: {out_path}")
    else:
        conn.rollback()
        print(f"dry-run만 수행(rollback, 실제 반영 안 됨). {len(FIXES)}건 확인. diff: {out_path}")

    cur.close()
    conn.close()


if __name__ == "__main__":
    main()
